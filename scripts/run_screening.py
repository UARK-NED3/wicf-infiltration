"""Generate the reproducible WICF door-open screening outputs using stdlib only."""
from __future__ import annotations

import csv
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from wicf_model import AirState, Doorway, door_open_load_kj, established_exchange_mass_flow_kg_s  # noqa: E402

RAW = ROOT / "data/raw/bentonville_ar_2025_daily_weather.json"
RESULTS = ROOT / "results"
REPORTS = ROOT / "reports"


def write_svg(rows: list[dict[str, float]]) -> None:
    width, height, left, bottom = 760, 420, 75, 350
    max_y = max(row["freezer_load_kj"] for row in rows) * 1.05
    pts = lambda key: " ".join(f"{left + row['open_time_s'] / 120 * 650:.1f},{bottom - row[key] / max_y * 290:.1f}" for row in rows)
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">
<style>text{{font-family:Arial,sans-serif;font-size:14px}} .axis{{stroke:#333;stroke-width:1.5}} .grid{{stroke:#ddd}} .cooler{{fill:none;stroke:#0072B2;stroke-width:3}} .freezer{{fill:none;stroke:#D55E00;stroke-width:3}}</style>
<rect width="100%" height="100%" fill="white"/><line class="axis" x1="{left}" y1="40" x2="{left}" y2="{bottom}"/><line class="axis" x1="{left}" y1="{bottom}" x2="725" y2="{bottom}"/>
<line class="grid" x1="75" y1="205" x2="725" y2="205"/><text x="10" y="30">Infiltration refrigeration load per door-open event (kJ)</text><text x="310" y="400">Door-open duration (s)</text>
<text x="25" y="355">0</text><text x="15" y="210">{max_y/2:.0f}</text><text x="15" y="55">{max_y:.0f}</text>
<text x="72" y="372">0</text><text x="232" y="372">30</text><text x="395" y="372">60</text><text x="557" y="372">90</text><text x="710" y="372">120</text>
<polyline class="cooler" points="{pts('cooler_load_kj')}"/><polyline class="freezer" points="{pts('freezer_load_kj')}"/>
<line class="cooler" x1="490" y1="65" x2="520" y2="65"/><text x="530" y="70">2 C cooler</text><line class="freezer" x1="490" y1="90" x2="520" y2="90"/><text x="530" y="95">-18 C freezer</text>
</svg>'''
    (RESULTS / "door_open_load.svg").write_text(svg, encoding="utf-8")


def main() -> None:
    RESULTS.mkdir(exist_ok=True)
    REPORTS.mkdir(exist_ok=True)
    door = Doorway()
    room = AirState(24.0, 50.0)
    configurations = {"cooler": AirState(2.0, 80.0), "freezer": AirState(-18.0, 70.0)}
    durations = [3, 10, 15, 30, 45, 60, 90, 120]
    rows = []
    for seconds in durations:
        rows.append({"open_time_s": seconds, **{f"{name}_load_kj": door_open_load_kj(room, state, door, seconds) for name, state in configurations.items()}})
    with (RESULTS / "summary.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=rows[0].keys())
        writer.writeheader(); writer.writerows(rows)
    write_svg(rows)

    weather = json.loads(RAW.read_text(encoding="utf-8"))["daily"]
    climate_rows = []
    for day, temp, rh in zip(weather["time"], weather["temperature_2m_mean"], weather["relative_humidity_2m_mean"]):
        outer = AirState(float(temp), float(rh))
        climate_rows.append({"date": day, "temperature_c": temp, "rh_pct": rh, "cooler_60s_load_kj": door_open_load_kj(outer, configurations["cooler"], door, 60), "freezer_60s_load_kj": door_open_load_kj(outer, configurations["freezer"], door, 60)})
    with (RESULTS / "climate_sensitivity.csv").open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=climate_rows[0].keys())
        writer.writeheader(); writer.writerows(climate_rows)
    checksum = hashlib.sha256(RAW.read_bytes()).hexdigest()
    flow = {name: established_exchange_mass_flow_kg_s(room, state, door) for name, state in configurations.items()}
    lookup = {row["open_time_s"]: row for row in rows}
    report = f'''# Preliminary screening results

Generated by `py -3 scripts/run_screening.py` from repository root on local execution.

## Evidence and boundary

These are **simulated/derived screening results**. The baseline assumes a 0.90 m × 2.10 m personnel door opening from a 24 C, 50% RH inventory room; no actual facility geometry, traffic, HVAC pressure, curtain state, or refrigeration response is represented. The model uses an analytical two-layer hydrostatic exchange approximation, `C_d = 0.60`, effective-exchange multiplier = 0.40, and a 3 s linear flow-establishment ramp. ASHRAE reports that established cold-room doorway flow occurs about 3 s after opening; the multiplier is an unvalidated sensitivity parameter, not a measured curtain credit.

## Baseline results

| Door-open duration (s) | 2 C cooler load (kJ/event) | -18 C freezer load (kJ/event) |
|---:|---:|---:|
| 15 | {lookup[15]['cooler_load_kj']:.0f} | {lookup[15]['freezer_load_kj']:.0f} |
| 30 | {lookup[30]['cooler_load_kj']:.0f} | {lookup[30]['freezer_load_kj']:.0f} |
| 45 | {lookup[45]['cooler_load_kj']:.0f} | {lookup[45]['freezer_load_kj']:.0f} |
| 60 | {lookup[60]['cooler_load_kj']:.0f} | {lookup[60]['freezer_load_kj']:.0f} |

The corresponding modelled established exchange flows are {flow['cooler']:.3f} kg/s (cooler) and {flow['freezer']:.3f} kg/s (freezer). Loads scale approximately linearly after the 3 s establishment period within this fixed-state model. The freezer has the larger per-event thermal burden because its indoor-air enthalpy is lower and density contrast is larger.

## Climate sensitivity (not actual room conditions)

The 2025 daily reanalysis input for the Bentonville proxy yields 60 s door-open loads spanning {min(r['cooler_60s_load_kj'] for r in climate_rows):.0f}–{max(r['cooler_60s_load_kj'] for r in climate_rows):.0f} kJ for the cooler and {min(r['freezer_60s_load_kj'] for r in climate_rows):.0f}–{max(r['freezer_60s_load_kj'] for r in climate_rows):.0f} kJ for the freezer. This sensitivity supports logging the *adjacent-room* temperature/RH and pressure rather than relying on outdoor weather.

## Preliminary conclusion

An escalating workflow is technically more defensible than one immediate nuisance-prone alarm. For this baseline, evaluate an attention/close-door alert at **15–30 s** and a high-priority alarm at **45–60 s**. The hypothesis is that these thresholds capture the onset of repeated quasi-steady exchange while preserving normal short personnel passages. The thresholds are **not validated settings** and must not be deployed based on this analysis alone.

## Required validation before an operational recommendation

1. Measure actual open duration and traffic distribution by door and shift.
2. Measure adjacent-room/WICF T-RH and differential pressure at 1 Hz or faster; record door state and curtain configuration.
3. Estimate event load from synchronized refrigeration power, suction/evaporator measurements, or a calibrated thermal balance; quantify sensor uncertainty and event-to-event variability.
4. Compare no curtain, strip curtain, and operationally acceptable closure scenarios. Do not assume an air/strip curtain reduces load without measurement.
5. Select thresholds against false-alarm burden, safety/egress constraints, product-temperature excursions, and energy/refrigeration response—not an energy-only model.

## Provenance

- Public weather file: `data/raw/bentonville_ar_2025_daily_weather.json`
- SHA-256: `{checksum}`
- Model: `src/wicf_model.py`
- Results: `results/summary.csv`, `results/climate_sensitivity.csv`, `results/door_open_load.svg`
'''
    (REPORTS / "preliminary_results.md").write_text(report, encoding="utf-8")


if __name__ == "__main__":
    main()
